class TestNextSlot(unittest.TestCase):
    def test_no_existing_pieces_returns_now(self):
        now = datetime(2026, 8, 29, 10, 0, 0)

        result = scheduler.next_slot(None, now=now)

        self.assertEqual(result, now)

    def test_existing_max_scheduled_advances_by_one_day(self):
        max_scheduled = datetime(2026, 8, 30, 10, 0, 0)
        now = datetime(2026, 8, 29, 10, 0, 0)

        result = scheduler.next_slot(max_scheduled, now=now)

        self.assertEqual(result, max_scheduled + timedelta(days=1))


